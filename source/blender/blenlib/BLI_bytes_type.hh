#pragma once

/** \file
 * \ingroup bli
 *
 * Code that only moves values around without interpreting them (copying, gathering, filling,
 * etc.) does not depend on the type of values, only on their size and alignment. This code can be
 * generated once per "bytes type" instead of once per type, reducing binary size.
 *
 * A "bytes type" is a trivial type with the same size and alignment as the original type. Scalars
 * and arrays of scalars are used, because they generally result in the same generated code as the
 * originals (avoiding byte arrays, because GCC doesn't seem to vectorize some loops with them).
 *
 * \note This relies on Blender being compiled without strict aliasing.
 */

#include <type_traits>
#include <utility>

#include "BLI_generic_span.hh"

namespace blender::bytes_type {

namespace detail {

template<int64_t Size> struct UIntForSize;
template<> struct UIntForSize<1> {
  using type = uint8_t;
};
template<> struct UIntForSize<2> {
  using type = uint16_t;
};
template<> struct UIntForSize<4> {
  using type = uint32_t;
};
template<> struct UIntForSize<8> {
  using type = uint64_t;
};

/** An array of the largest unsigned integers that the alignment allows. */
template<int64_t Size, int64_t Alignment> struct alignas(Alignment) BytesTypeArray {
  static constexpr int64_t ValueSize = Alignment < 8 ? Alignment : 8;
  typename UIntForSize<ValueSize>::type values[size_t(Size / ValueSize)];
};

template<int64_t Size, int64_t Alignment> struct BytesTypeImpl {
  using type = BytesTypeArray<Size, Alignment>;
};
template<int64_t Size>
  requires(Size <= 8)
struct BytesTypeImpl<Size, Size> {
  using type = typename UIntForSize<Size>::type;
};

}  // namespace detail

/** The size and alignment of a type, which is all that matters for its bytes type. */
struct Layout {
  int64_t size;
  int64_t alignment;

  template<typename T> static constexpr Layout of()
  {
    return {int64_t(sizeof(T)), int64_t(alignof(T))};
  }

  static Layout of(const CPPType &type)
  {
    return {type.size, type.alignment};
  }

  friend constexpr bool operator==(const Layout &a, const Layout &b) = default;
};

/** The bytes type for a trivial type T. */
template<typename T>
using BytesType = typename detail::BytesTypeImpl<int64_t(sizeof(T)), int64_t(alignof(T))>::type;

/**
 * We only generate "bytes types" for certain size and alignment combinations, because the bytes
 * types are often used to generate optimized code that has a large binary size impact.
 */
inline constexpr Layout shared_layouts[] = {
    {1, 1},   /* bool, int8_t */
    {4, 1},   /* ColorGeometry4b */
    {4, 2},   /* short2 */
    {4, 4},   /* float, int */
    {8, 4},   /* float2, int2 */
    {12, 4},  /* float3 */
    {16, 4},  /* float4, ColorGeometry4f, math::Quaternion */
    {64, 16}, /* float4x4 */
};

constexpr bool is_shared(const Layout layout)
{
  for (const Layout &shared_layout : shared_layouts) {
    if (shared_layout == layout) {
      return true;
    }
  }
  return false;
}

/** True if code for the bytes type of T is generated by #to_static_type_try. */
template<typename T>
inline constexpr bool is_shared_v = std::is_trivial_v<T> && is_shared(Layout::of<T>());

/** The bytes type of the shared layout at index \a I in #shared_layouts. */
template<size_t I>
using SharedType =
    typename detail::BytesTypeImpl<shared_layouts[I].size, shared_layouts[I].alignment>::type;

#define BLI_BYTES_TYPE_FOREACH_SHARED(MACRO) \
  MACRO(::blender::bytes_type::SharedType<0>) \
  MACRO(::blender::bytes_type::SharedType<1>) \
  MACRO(::blender::bytes_type::SharedType<2>) \
  MACRO(::blender::bytes_type::SharedType<3>) \
  MACRO(::blender::bytes_type::SharedType<4>) \
  MACRO(::blender::bytes_type::SharedType<5>) \
  MACRO(::blender::bytes_type::SharedType<6>) \
  MACRO(::blender::bytes_type::SharedType<7>)
static_assert(std::size(shared_layouts) == 8, "Update BLI_BYTES_TYPE_FOREACH_SHARED");

/** A type's bytes type if its layout is one of the #shared_layouts, otherwise T itself. */
template<typename T> using StaticType = std::conditional_t<is_shared_v<T>, BytesType<T>, T>;

/**
 * Call the templated function with the bytes type that has the given layout.
 * \return False if the layout is not one of the #shared_layouts.
 */
template<typename Fn> inline bool to_static_type_try(const Layout layout, Fn &&fn)
{
  return [&]<size_t... I>(std::index_sequence<I...> /*indices*/) {
    return ((layout == shared_layouts[I] &&
             (fn.template
              operator()<typename detail::BytesTypeImpl<shared_layouts[I].size,
                                                        shared_layouts[I].alignment>::type>(),
              true)) ||
            ...);
  }(std::make_index_sequence<std::size(shared_layouts)>());
}

/**
 * Similar to #CPPType::to_static_type_try, but calls the templated function with the type's bytes
 * type instead of the type itself if its layout is one of the #shared_layouts.
 *
 * \tparam Types: Types that the function is called with directly if their layout is not shared,
 * so that they are supported as well.
 * \return False if the type is not trivial with a shared layout and not one of Types.
 */
template<typename... Types, typename Fn>
inline bool to_static_type_try(const CPPType &type, Fn &&fn)
{
  if (type.is_trivial && to_static_type_try(Layout::of(type), fn)) {
    return true;
  }
  [[maybe_unused]] const auto try_type = [&]<typename T>() {
    if constexpr (is_shared_v<T>) {
      /* Handled by the layout dispatch above. */
      return false;
    }
    else {
      if (type.is<T>()) {
        fn.template operator()<T>();
        return true;
      }
      return false;
    }
  };
  return (try_type.template operator()<Types>() || ...);
}

/** Same as #to_static_type_try, but asserts if the type is not supported. */
template<typename... Types, typename Fn> inline void to_static_type(const CPPType &type, Fn &&fn)
{
  if (!to_static_type_try<Types...>(type, fn)) {
    BLI_assert_unreachable();
  }
}

/** True if T is the type that #to_static_type calls the function with for the given type. */
template<typename T> inline bool is_static_type_for(const CPPType &type)
{
  if constexpr (is_shared_v<T>) {
    return type.is_trivial && Layout::of(type) == Layout::of<T>();
  }
  else {
    return type.is<T>();
  }
}

/** Get a span of the type that #to_static_type called the function with. */
template<typename T> inline Span<T> typed(const GSpan span)
{
  BLI_assert(span.is_empty() || is_static_type_for<T>(span.type()));
  return Span<T>(static_cast<const T *>(span.data()), span.size());
}

/** Get a span of the type that #to_static_type called the function with. */
template<typename T> inline MutableSpan<T> typed(const GMutableSpan span)
{
  BLI_assert(span.is_empty() || is_static_type_for<T>(span.type()));
  return MutableSpan<T>(static_cast<T *>(span.data()), span.size());
}

}  // namespace blender::bytes_type
