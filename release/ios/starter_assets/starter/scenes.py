"""Objects/Scenes: ready-made render setups, dropped as real objects (not instances).

Dropping a collection appends it and moves its top-level objects by the drop location, keeping
their relative transforms, so everything is laid out around the collection origin: the subject
stands at the origin, the backdrop opens towards -Y and the camera looks along +Y.
"""

import bpy
from bpy_extras import anim_utils
from mathutils import Vector

from .common import RADIANS, object_group, simple_material
from .registry import asset

CATALOG = "Objects/Scenes"


def backdrop_group():
    """A seamless sweep from floor to wall, with the subject area at the origin."""
    tree = bpy.data.node_groups.get("Backdrop")
    if tree:
        return tree
    tree = object_group("Backdrop")
    width = tree.input("Width", "FLOAT", 9.0, min=0.1, subtype="DISTANCE")
    height = tree.input("Height", "FLOAT", 4.5, min=0.1, subtype="DISTANCE")
    wall = tree.input("Wall Distance", "FLOAT", 3.5, min=0.0, subtype="DISTANCE",
                      description="Distance from the center to the wall")
    front = tree.input("Front Distance", "FLOAT", 4.0, min=0.0, subtype="DISTANCE",
                       description="Distance from the center to the front edge of the floor")
    radius = tree.input("Curve Radius", "FLOAT", 1.5, min=0.0, subtype="DISTANCE",
                        description="Radius of the sweep between the floor and the wall")
    segments = tree.input("Segments", "INT", 24, min=1, max=128,
                          description="Smoothness of the sweep")
    material = tree.input("Material", "MATERIAL", None)

    # Profile in the YZ plane: front of the floor, corner, top of the wall; then round the corner.
    line = tree.n("GeometryNodeMeshLine", Count=3).outputs[0]
    index = tree.n("GeometryNodeInputIndex").outputs[0]
    y = tree.math("SUBTRACT", tree.math("MULTIPLY", tree.math("MINIMUM", index, 1.0),
                                        tree.math("ADD", front, wall)), front)
    z = tree.math("MULTIPLY", tree.math("MAXIMUM", tree.math("SUBTRACT", index, 1.0), 0.0),
                  height)
    line = tree.n("GeometryNodeSetPosition", Geometry=line,
                  Position=tree.xyz(0.0, y, z)).outputs[0]
    curve = tree.n("GeometryNodeMeshToCurve", Mesh=line).outputs[0]
    curve = tree.n("GeometryNodeFilletCurve", Curve=curve, Radius=radius, Count=segments,
                   Limit_Radius=True, mode="POLY").outputs[0]
    edges = tree.n("GeometryNodeCurveToMesh", Curve=curve).outputs[0]
    # Sweep the profile sideways into a surface facing the subject, centered on X.
    mesh = tree.n("GeometryNodeExtrudeMesh", Mesh=edges, mode="EDGES", Offset=tree.xyz(width),
                  Offset_Scale=1.0).outputs["Mesh"]
    mesh = tree.transform(mesh, translation=tree.xyz(tree.math("MULTIPLY", width, -0.5)))
    mesh = tree.smooth(mesh, angle=30 * RADIANS)
    mesh = tree.material(mesh, material)
    tree.output(mesh)
    tree.layout()
    return tree.nt


def platform_group():
    """A low round platform for the subject to stand on."""
    tree = object_group("Platform")
    radius = tree.input("Radius", "FLOAT", 0.75, min=0.01, subtype="DISTANCE")
    height = tree.input("Height", "FLOAT", 0.06, min=0.001, subtype="DISTANCE")
    material = tree.input("Material", "MATERIAL", None)
    mesh = tree.n("GeometryNodeMeshCylinder", Vertices=96, Radius=radius,
                  Depth=height).outputs["Mesh"]
    mesh = tree.transform(mesh, translation=tree.xyz(z=tree.math("MULTIPLY", height, 0.5)))
    mesh = tree.smooth(mesh, angle=30 * RADIANS)
    mesh = tree.material(mesh, material)
    tree.output(mesh)
    tree.layout()
    return tree.nt


def generated(name, group, **inputs):
    """An object generated by an existing node group, with some inputs set on its modifier."""
    mesh = bpy.data.meshes.new(name)
    obj = bpy.data.objects.new(name, mesh)
    modifier = obj.modifiers.new(group.name, "NODES")
    modifier.node_group = group
    for item in group.interface.items_tree:
        key = item.name.replace(" ", "_")
        if item.item_type == "SOCKET" and item.in_out == "INPUT" and key in inputs:
            modifier[item.identifier] = inputs[key]
    return obj


def aim(obj, target):
    """Point an object's -Z axis (cameras and lights) at `target`, keeping +Y up."""
    direction = Vector(target) - obj.location
    obj.rotation_euler = direction.to_track_quat("-Z", "Y").to_euler()


def area_light(name, location, target, energy, size, size_y=None, color=(1.0, 1.0, 1.0)):
    light = bpy.data.lights.new(name, "AREA")
    light.energy = energy
    light.color = color
    if size_y:
        light.shape = "RECTANGLE"
        light.size, light.size_y = size, size_y
    else:
        light.shape = "DISK"
        light.size = size
    obj = bpy.data.objects.new(name, light)
    obj.location = location
    aim(obj, target)
    return obj


def rim_light(name, location, target, energy):
    """A soft-edged spot: an area light this close to the backdrop would streak across it."""
    light = bpy.data.lights.new(name, "SPOT")
    light.energy = energy
    light.spot_size = 45 * RADIANS
    light.spot_blend = 1.0
    light.shadow_soft_size = 0.4
    obj = bpy.data.objects.new(name, light)
    obj.location = location
    aim(obj, target)
    return obj


def three_lights(prefix, target):
    """Soft key, fill and rim lights around a subject standing at the origin."""
    return [
        area_light(f"{prefix}Key Light", (-2.6, -2.6, 3.0), target, 250.0, 1.6, 1.2,
                   (1.0, 0.95, 0.88)),
        area_light(f"{prefix}Fill Light", (3.2, -2.2, 1.6), target, 70.0, 2.4,
                   color=(0.88, 0.94, 1.0)),
        rim_light(f"{prefix}Rim Light", (1.6, 2.0, 3.4), target, 800.0),
    ]


def camera(name, location, target, lens=50.0):
    data = bpy.data.cameras.new(name)
    data.lens = lens
    data.clip_end = 200.0
    obj = bpy.data.objects.new(name, data)
    obj.location = location
    aim(obj, target)
    return obj


def collection(name, objects):
    result = bpy.data.collections.new(name)
    for obj in objects:
        result.objects.link(obj)
    return result


@asset("Studio Backdrop", "collection", CATALOG,
       "A seamless curved backdrop with soft key, fill and rim lights and a camera framing a "
       "subject at its center.",
       ("studio", "backdrop", "cyclorama", "lighting", "camera", "render", "scene"))
def studio_backdrop():
    backdrop = generated("Backdrop", backdrop_group(),
                         Material=simple_material("Backdrop Grey", (0.32, 0.32, 0.32),
                                                  roughness=0.7))
    target = (0.0, 0.0, 0.95)
    return collection("Studio Backdrop", [
        backdrop,
        *three_lights("", target),
        camera("Studio Camera", (0.0, -6.2, 1.15), target),
    ])


@asset("Turntable", "collection", CATALOG,
       "A camera and soft lights that orbit a platform in front of a dark backdrop, looping "
       "every 120 frames.",
       ("turntable", "orbit", "showcase", "animation", "camera", "lighting", "scene"))
def turntable():
    pivot = bpy.data.objects.new("Turntable Pivot", None)
    pivot.empty_display_type = "CIRCLE"
    pivot.empty_display_size = 1.2
    # Turn only Z, linearly and forever: frames 1 to 120 are one seamless loop.
    pivot.keyframe_insert("rotation_euler", index=2, frame=1)
    pivot.rotation_euler.z = 360 * RADIANS
    pivot.keyframe_insert("rotation_euler", index=2, frame=121)
    pivot.rotation_euler.z = 0.0
    animation = pivot.animation_data
    animation.action.name = "Turntable Orbit"
    bag = anim_utils.action_get_channelbag_for_slot(animation.action, animation.action_slot)
    for fcurve in bag.fcurves:
        for key in fcurve.keyframe_points:
            key.interpolation = "LINEAR"
        fcurve.modifiers.new("CYCLES")

    target = (0.0, 0.0, 1.0)
    # The backdrop, lights and camera turn together, so the subject is always seen against
    # the backdrop and lit the same way, as if it turned on the platform.
    backdrop = generated("Turntable Backdrop", backdrop_group(), Width=8.0, Height=3.5,
                         Front_Distance=2.0,
                         Material=simple_material("Turntable Dark", (0.02, 0.02, 0.022),
                                                  roughness=0.6))
    platform = generated("Turntable Platform", platform_group(),
                         Material=simple_material("Turntable Platform", (0.7, 0.7, 0.68),
                                                  roughness=0.45))
    orbiting = [backdrop, *three_lights("Turntable ", target),
                camera("Turntable Camera", (0.0, -5.6, 1.5), target)]
    for obj in orbiting:
        obj.parent = pivot
    return collection("Turntable", [platform, pivot, *orbiting])

