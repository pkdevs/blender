"""Helpers shared by the asset modules.

Conventions every object asset follows:
- The object's geometry comes from a Geometry Nodes modifier, so its inputs show in Properties.
- The geometry rests on the ground: centered on X/Y, lowest point at Z = 0. Dropped objects are
  placed by their origin onto the surface under the finger, so they sit on it.
- Sizes are real-world meters, defaults sized like the real thing (a mug is ~0.1 m).
- Defaults stay under 50k triangles and evaluate quickly, so they're fluid on an iPad.
- Every dimension and count that shapes the object has a gizmo in the viewport (see the gizmo
  helpers below), so it can be reshaped by dragging, not only by typing numbers.
"""

import math

import bpy

from .nodes import Tree


def generator_object(name, tree):
    """An object whose geometry is generated by `tree` (a Geometry Nodes group)."""
    tree.layout()
    mesh = bpy.data.meshes.new(name)
    obj = bpy.data.objects.new(name, mesh)
    modifier = obj.modifiers.new(name, "NODES")
    modifier.node_group = tree.nt
    return obj


def modifier_group(name):
    """A Geometry Nodes group meant to be added to an existing object as a modifier."""
    return Tree.geometry(name, modifier=True, geometry_input=True)


def object_group(name):
    """A Geometry Nodes group that generates an object's geometry from nothing."""
    return Tree.geometry(name, modifier=True, geometry_input=False)


def rest_on_ground(tree, geometry):
    """Move geometry so it's centered on X/Y with its lowest point at Z = 0.

    Gizmos made so far are joined in first, so they move with the geometry.
    """
    geometry = tree.with_gizmos(geometry)
    bounds = tree.n("GeometryNodeBoundBox", Geometry=geometry)
    low = tree.out(bounds, "Min")
    high = tree.out(bounds, "Max")
    center = tree.vmath("SCALE", tree.vmath("ADD", low, high), scale=0.5)
    cx, cy, _ = tree.separate(center)
    _, _, lz = tree.separate(low)
    offset = tree.xyz(tree.math("MULTIPLY", cx, -1.0), tree.math("MULTIPLY", cy, -1.0),
                      tree.math("MULTIPLY", lz, -1.0))
    return tree.transform(geometry, translation=offset)


RADIANS = math.pi / 180.0


