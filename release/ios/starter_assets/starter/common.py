def palette(name):
    """A default material by name, created once per build."""
    material = bpy.data.materials.get(name)
    if material:
        return material
    color, metallic, roughness, extra = _PALETTE[name]
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    bsdf = material.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    for key, value in extra.items():
        socket = bsdf.inputs[key]
        socket.default_value = (*value, 1.0) if isinstance(value, tuple) and len(value) == 3 else value
    material.diffuse_color = (*color, 1.0)
    material.metallic = metallic
    material.roughness = roughness
    return material


def simple_material(name, color, metallic=0.0, roughness=0.5, **inputs):
    """A plain Principled BSDF material for a module's own needs, created once per build.

    Keyword arguments set Principled BSDF inputs by name with spaces as underscores,
    e.g. `simple_material("Lamp Shade", (0.9, 0.85, 0.7), Transmission_Weight=0.3)`.
    """
    material = bpy.data.materials.get(name)
    if material:
        return material
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    bsdf = material.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    for key, value in inputs.items():
        socket = bsdf.inputs[key.replace("_", " ")]
        if isinstance(value, tuple) and len(value) == 3:
            value = (*value, 1.0)
        socket.default_value = value
    material.diffuse_color = (*color, 1.0)
    material.metallic = metallic
    material.roughness = roughness
    return material
