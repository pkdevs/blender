"""Validate a built Starter asset library.

    blender --background --factory-startup --python validate_starter_library.py -- \\
        --library library [--contact-sheet sheet.png] [--strict-time]

Appends every asset into a fresh file, the way dropping it from the asset pane does, and checks:
- metadata: catalog (present in the catalog file), description, author, license, search tags;
- previews: present, 256 px, and not blank;
- objects: generated by Geometry Nodes with tweakable inputs, rest on the ground, real-world size,
  under the triangle and evaluation-time budgets; primitives also have a UV map spanning 0-1;
- gizmos: procedural objects and modifiers have a working gizmo for every size and count input;
- materials: a connected Material Output;
- modifiers: flagged as modifiers, have a geometry input, change the geometry they're applied to;
- collections: evaluate.
Exits non-zero with a list of every problem found.
"""

import argparse
import json
import math
import os
import sys
import time

import bpy
from mathutils import Vector

TRIANGLE_BUDGET = 50_000
MODIFIER_TRIANGLE_BUDGET = 150_000
TIME_BUDGET = 0.050


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    parser = argparse.ArgumentParser()
    parser.add_argument("--library", required=True)
    parser.add_argument("--contact-sheet")
    parser.add_argument("--strict-time", action="store_true",
                        help="Fail, rather than warn, when an asset evaluates slower than the budget")
    return parser.parse_args(argv)


def read_catalogs(path):
    catalogs = {}
    with open(path, encoding="utf-8") as file:
        for line in file:
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("VERSION"):
                continue
            uuid, catalog_path, _ = line.split(":", 2)
            catalogs[uuid] = catalog_path
    return catalogs


def append(path, collection_name, names):
    with bpy.data.libraries.load(path, link=False, assets_only=True) as (source, target):
        available = set(getattr(source, collection_name))
        setattr(target, collection_name, [name for name in names if name in available])
    return {id_data.name: id_data for id_data in getattr(target, collection_name) if id_data}


def evaluated_stats(objects):
    """Triangles and world bounds of everything the objects evaluate to, instances included."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    triangles = 0
    low = Vector((math.inf,) * 3)
    high = Vector((-math.inf,) * 3)
    originals = set(objects)
    for instance in depsgraph.object_instances:
        source = instance.parent.original if instance.parent else instance.object.original
        if source not in originals:
            continue
        obj = instance.object
        if obj.type == "MESH":
            mesh = obj.data
            mesh.calc_loop_triangles()
            triangles += len(mesh.loop_triangles)
            if len(mesh.vertices) == 0:
                continue
        elif obj.type not in {"CURVES", "POINTCLOUD", "VOLUME", "CURVE", "FONT"}:
            continue
        for corner in obj.bound_box:
            point = instance.matrix_world @ Vector(corner)
            low = Vector(map(min, low, point))
            high = Vector(map(max, high, point))
    return triangles, low, high


# Nodes a gizmo can edit through, and the input it edits (see Blender's `eval_inverse_elem`).
_ARITHMETIC = {"ADD", "SUBTRACT", "MULTIPLY", "DIVIDE"}
_INVERTIBLE = {
    "ShaderNodeMath": lambda node: ["Value"] if node.operation in _ARITHMETIC else [],
    "FunctionNodeIntegerMath": lambda node: ["Value"] if node.operation in _ARITHMETIC else [],
    "ShaderNodeVectorMath": lambda node: (["Vector"] if node.operation in _ARITHMETIC | {"SCALE"}
                                          else []),
    "ShaderNodeSeparateXYZ": lambda node: ["Vector"],
    "ShaderNodeCombineXYZ": lambda node: ["X", "Y", "Z"],
    "NodeReroute": lambda node: ["Input"],
}
GIZMO_NODES = {"GeometryNodeGizmoLinear", "GeometryNodeGizmoDial", "GeometryNodeGizmoTransform"}
# Inputs that don't shape anything a gizmo could show.
_NO_GIZMO_NEEDED = ("seed",)


def _gizmo_targets(socket, seen=None):
    """Group input identifiers a gizmo linked from `socket` edits, or None for a dead end."""
    seen = seen if seen is not None else set()
    node = socket.node
    if node.bl_idname == "NodeGroupInput":
        return {socket.identifier}
    rule = _INVERTIBLE.get(node.bl_idname)
    if rule is None or node in seen:
        return None
    seen.add(node)
    targets = set()
    for identifier in rule(node):
        inputs = [item for item in node.inputs if item.enabled and item.identifier == identifier]
        for item in inputs:
            for link in item.links:
                found = _gizmo_targets(link.from_socket, seen)
                if found:
                    targets |= found
    return targets or None


def _reaches_output(socket, seen=None):
    seen = seen if seen is not None else set()
    for link in socket.links:
        node = link.to_node
        if node.bl_idname == "NodeGroupOutput":
            return True
        if node in seen or node.mute:
            continue
        seen.add(node)
        if any(_reaches_output(output, seen) for output in node.outputs if output.enabled):
            return True
    return False


def gizmo_problems(group):
    """Every gizmo edits a group input and is part of the output; size and count inputs have one."""
    problems = []
    edited = set()
    gizmos = [node for node in group.nodes if node.bl_idname in GIZMO_NODES]
    if not gizmos:
        return ["has no gizmos to reshape it in the viewport"]
    for node in gizmos:
        name = node.label or node.name
        links = node.inputs["Value"].links
        if not links:
            problems.append(f"gizmo {name!r} edits nothing")
        for link in links:
            targets = _gizmo_targets(link.from_socket)
            if not targets:
                problems.append(f"gizmo {name!r} can't edit {link.from_node.name!r}: "
                                f"its value doesn't lead back to a group input")
            else:
                edited |= targets
        if not _reaches_output(node.outputs[0]):
            problems.append(f"gizmo {name!r} isn't joined into the output, so it won't follow "
                            f"the geometry")
    for item in group.interface.items_tree:
        if item.item_type != "SOCKET" or item.in_out != "INPUT" or item.identifier in edited:
            continue
        if any(word in item.name.lower() for word in _NO_GIZMO_NEEDED):
            continue
        if item.socket_type == "NodeSocketInt" or (
                item.socket_type == "NodeSocketFloat" and item.subtype == "DISTANCE"):
            problems.append(f"input {item.name!r} has no gizmo")
    return problems


def uv_problem(obj):
    """Primitives are textured as dropped, so they need a UV map that uses the 0-1 square."""
    evaluated = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    try:
        if "UVMap" not in mesh.uv_layers:
            return "has no UVMap"
        uvs = [item.vector for item in mesh.uv_layers["UVMap"].uv]
        low = (min(uv.x for uv in uvs), min(uv.y for uv in uvs))
        high = (max(uv.x for uv in uvs), max(uv.y for uv in uvs))
        if min(low) < -0.001 or max(high) > 1.001 or high[0] - low[0] < 0.5:
            return f"UVs span {low} to {high}, not the 0-1 square"
        return None
    finally:
        evaluated.to_mesh_clear()


def _tweakable_input(obj):
    """A Geometry Nodes modifier and the identifier of a numeric input to nudge."""
    for modifier in obj.modifiers:
        if modifier.type != "NODES" or not modifier.node_group:
            continue
        for item in modifier.node_group.interface.items_tree:
            if item.item_type == "SOCKET" and item.in_out == "INPUT" and \
                    item.socket_type in {"NodeSocketFloat", "NodeSocketInt"}:
                return modifier, item.identifier
    return None, None


def time_evaluation(obj):
    """Seconds to evaluate the object again after changing an input, as tweaking one does."""
    depsgraph = bpy.context.evaluated_depsgraph_get()
    modifier, identifier = _tweakable_input(obj)
    best = math.inf
    for attempt in range(4):
        if modifier:
            value = modifier[identifier]
            # Nudge and restore, so each evaluation recomputes the node tree.
            modifier[identifier] = value + (1 if isinstance(value, int) else 1e-4) * (
                1 if attempt % 2 == 0 else -1)
            modifier.node_group.interface_update(bpy.context)
        obj.update_tag(refresh={"DATA"})
        start = time.perf_counter()
        depsgraph.update()
        best = min(best, time.perf_counter() - start)
    return best


def menu_options(group):
    """Each menu input of a Geometry Nodes group with the item names it offers."""
    group_input = next((node for node in group.nodes if node.bl_idname == "NodeGroupInput"), None)
    menus = []
    for item in group.interface.items_tree:
        if item.item_type != "SOCKET" or item.in_out != "INPUT" or \
                item.socket_type != "NodeSocketMenu":
            continue
        names = []
        if group_input:
            for link in group.links:
                if link.from_node == group_input and \
                        link.from_socket.identifier == item.identifier and \
                        link.to_node.bl_idname == "GeometryNodeMenuSwitch":
                    names = [enum.name for enum in link.to_node.enum_items]
                    break
        menus.append((item, names))
    return menus


def menu_problems(label, group, make_object, scene):
    """Evaluate every option of every menu: each must produce geometry resting on the ground."""
    problems = []
    for item, names in menu_options(group):
        if not names:
            problems.append(f"{label}: menu {item.name!r} has no items")
            continue
        if not item.default_value:
            problems.append(f"{label}: menu {item.name!r} has no default")
        original = item.default_value
        for name in names:
            item.default_value = name
            obj = make_object()
            scene.collection.objects.link(obj)
            triangles, low, high = evaluated_stats([obj])
            if triangles == 0:
                problems.append(f"{label}: {item.name} = {name!r} evaluates to nothing")
            elif triangles > MODIFIER_TRIANGLE_BUDGET:
                problems.append(f"{label}: {item.name} = {name!r} has {triangles} triangles")
            bpy.data.objects.remove(obj)
        item.default_value = original
    return problems


def preview_problem(id_data):
    preview = id_data.preview
    if preview is None or tuple(preview.image_size) != (256, 256):
        return "missing 256 px preview"
    pixels = preview.image_pixels_float
    count = len(pixels) // 4
    luminance = [0.2126 * pixels[4 * i] + 0.7152 * pixels[4 * i + 1] + 0.0722 * pixels[4 * i + 2]
                 for i in range(0, count, 37)]
    mean = sum(luminance) / len(luminance)
    spread = math.sqrt(sum((value - mean) ** 2 for value in luminance) / len(luminance))
    if spread < 0.01:
        return f"preview looks blank (spread {spread:.4f})"
    return None


def write_contact_sheet(path, ids, columns=10):
    size = 256
    rows = math.ceil(len(ids) / columns)
    sheet = bpy.data.images.new("Contact Sheet", columns * size, rows * size, alpha=False)
    pixels = [0.0] * (columns * size * rows * size * 4)
    for index, id_data in enumerate(ids):
        if id_data.preview is None or tuple(id_data.preview.image_size) != (size, size):
            continue
        source = id_data.preview.image_pixels_float
        column = index % columns
        row = rows - 1 - index // columns
        for y in range(size):
            begin = ((row * size + y) * columns * size + column * size) * 4
            pixels[begin:begin + size * 4] = source[y * size * 4:(y + 1) * size * 4]
    sheet.pixels = pixels
    sheet.filepath_raw = path
    sheet.file_format = "PNG"
    sheet.save()
    print(f"Contact sheet: {path} ({columns} columns, in manifest order)")


def main():
    args = parse_args()
    library = os.path.abspath(args.library)
    with open(os.path.join(library, "manifest.json"), encoding="utf-8") as file:
        manifest = json.load(file)["assets"]
    catalogs = read_catalogs(os.path.join(library, "blender_assets.cats.txt"))
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene

    problems = []
    warnings = []
    ids_in_order = []
    collections = {"object": "objects", "material": "materials", "modifier": "node_groups",
                   "collection": "collections"}

    by_file = {}
    for entry in manifest:
        by_file.setdefault(entry["file"], []).append(entry)

    loaded = {}
    for filename, entries in by_file.items():
        path = os.path.join(library, filename)
        if not os.path.exists(path):
            problems.append(f"{filename}: missing")
            continue
        for kind in {entry["kind"] for entry in entries}:
            names = [entry["name"] for entry in entries if entry["kind"] == kind]
            for name, id_data in append(path, collections[kind], names).items():
                loaded[(kind, name)] = id_data

    for entry in manifest:
        name, kind = entry["name"], entry["kind"]
        label = f"{kind} {name!r}"
        id_data = loaded.get((kind, name))
        if id_data is None:
            problems.append(f"{label}: not found in {entry['file']}")
            continue
        ids_in_order.append(id_data)
        data = id_data.asset_data
        if data is None:
            problems.append(f"{label}: not marked as an asset")
            continue
        if catalogs.get(data.catalog_id) != entry["catalog"]:
            problems.append(f"{label}: catalog {data.catalog_id} is not {entry['catalog']!r}")
        if not data.description.endswith("."):
            problems.append(f"{label}: description is not a sentence")
        if not data.author or data.license != "CC0":
            problems.append(f"{label}: author or CC0 license missing")
        if len(data.tags) < 2:
            problems.append(f"{label}: fewer than two search tags")
        problem = preview_problem(id_data)
        if problem:
            problems.append(f"{label}: {problem}")

        if kind == "object":
            modifiers = [m for m in id_data.modifiers if m.type == "NODES" and m.node_group]
            if not modifiers and entry["catalog"] not in {"Objects/Human Bases", "Objects/Sculpt Bases"}:
                problems.append(f"{label}: has no Geometry Nodes modifier")
            for modifier in modifiers:
                inputs = [item for item in modifier.node_group.interface.items_tree
                          if item.item_type == "SOCKET" and item.in_out == "INPUT"
                          and item.socket_type != "NodeSocketGeometry"]
                if not inputs and entry["catalog"] not in {"Objects/Sculpt Bases"}:
                    problems.append(f"{label}: exposes no inputs to tweak")
            scene.collection.objects.link(id_data)
            triangles, low, high = evaluated_stats([id_data])
            seconds = time_evaluation(id_data)
            if triangles == 0:
                problems.append(f"{label}: evaluates to no triangles")
            elif triangles > TRIANGLE_BUDGET:
                problems.append(f"{label}: {triangles} triangles, over the {TRIANGLE_BUDGET} budget")
            if seconds > TIME_BUDGET:
                message = f"{label}: evaluates in {seconds * 1000:.1f} ms, over {TIME_BUDGET * 1000:.0f} ms"
                (problems if args.strict_time else warnings).append(message)
            if low.x != math.inf:
                size = high - low
                largest = max(size)
                tolerance = max(0.002, largest * 0.01)
                if abs(low.z) > tolerance:
                    problems.append(f"{label}: lowest point at Z {low.z:.3f}, not on the ground")
                center = (low + high) * 0.5
                if abs(center.x) > tolerance or abs(center.y) > tolerance:
                    problems.append(f"{label}: not centered on X/Y ({center.x:.3f}, {center.y:.3f})")
                if largest > 60.0 or largest < 0.01:
                    problems.append(f"{label}: implausible size {largest:.3f} m")
                hint = data.get("dimensions")
                if hint is not None and getattr(hint, "typecode", "f") != "f":
                    problems.append(f"{label}: dimensions hint must be a float array, "
                                    f"not {hint.typecode!r}")
                if hint is None or any(abs(a - b) > max(0.01, b * 0.02)
                                       for a, b in zip(hint, size)):
                    problems.append(f"{label}: dimensions hint {hint and list(hint)} doesn't match "
                                    f"its size {[round(v, 3) for v in size]}; drops draw it")
            for modifier in modifiers:
                problems += [f"{label}: {problem}" for problem in gizmo_problems(modifier.node_group)]
            if entry["catalog"] == "Objects/Primitives":
                problem = uv_problem(id_data)
                if problem:
                    problems.append(f"{label}: {problem}")
            print(f"{label:42} {triangles:7d} tris {seconds * 1000:7.1f} ms")
            scene.collection.objects.unlink(id_data)
            for modifier in modifiers:
                def make_object(group=modifier.node_group):
                    obj = bpy.data.objects.new("Menu Check", bpy.data.meshes.new("Menu Check"))
                    obj.modifiers.new("Menu Check", "NODES").node_group = group
                    return obj
                problems.extend(menu_problems(label, modifier.node_group, make_object, scene))

        elif kind == "material":
            tree = id_data.node_tree
            outputs = [node for node in tree.nodes if node.bl_idname == "ShaderNodeOutputMaterial"]
            if not outputs or not any(node.inputs["Surface"].is_linked for node in outputs):
                problems.append(f"{label}: no connected Material Output")

        elif kind == "modifier":
            if not id_data.is_modifier:
                problems.append(f"{label}: not flagged as a modifier")
            problems += [f"{label}: {problem}" for problem in gizmo_problems(id_data)]
            items = [item for item in id_data.interface.items_tree if item.item_type == "SOCKET"]
            if not any(item.in_out == "INPUT" and item.socket_type == "NodeSocketGeometry" for item in items):
                problems.append(f"{label}: has no geometry input")
            bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=3, radius=0.5, location=(0, 0, 0.5))
            base = bpy.context.active_object
            before = (len(base.data.vertices), tuple(base.dimensions))
            modifier = base.modifiers.new(name, "NODES")
            modifier.node_group = id_data
            triangles, low, high = evaluated_stats([base])
            seconds = time_evaluation(base)
            evaluated = base.evaluated_get(bpy.context.evaluated_depsgraph_get())
            after = (len(evaluated.data.vertices) if evaluated.type == "MESH" else -1,
                     tuple(evaluated.dimensions))
            if before == after and triangles == 1280:
                problems.append(f"{label}: does not change the geometry it's added to")
            if triangles > MODIFIER_TRIANGLE_BUDGET:
                problems.append(f"{label}: {triangles} triangles on a 1280-triangle sphere")
            if seconds > TIME_BUDGET:
                message = f"{label}: evaluates in {seconds * 1000:.1f} ms, over {TIME_BUDGET * 1000:.0f} ms"
                (problems if args.strict_time else warnings).append(message)
            print(f"{label:42} {triangles:7d} tris {seconds * 1000:7.1f} ms")

            def make_object(group=id_data, mesh=base.data):
                obj = bpy.data.objects.new("Menu Check", mesh)
                obj.location = (0, 0, 0.5)
                obj.modifiers.new("Menu Check", "NODES").node_group = group
                return obj
            problems.extend(menu_problems(label, id_data, make_object, scene))
            bpy.data.objects.remove(base)

        elif kind == "collection":
            instance = bpy.data.objects.new(name, None)
            instance.instance_type = "COLLECTION"
            instance.instance_collection = id_data
            scene.collection.objects.link(instance)
            triangles, _, _ = evaluated_stats([instance])
            if triangles == 0:
                problems.append(f"{label}: instance evaluates to nothing")
            print(f"{label:42} {triangles:7d} tris")
            bpy.data.objects.remove(instance)

    used = {entry["catalog"] for entry in manifest}
    for catalog in used:
        if catalog not in catalogs.values():
            problems.append(f"catalog {catalog!r} missing from blender_assets.cats.txt")

    if args.contact_sheet:
        write_contact_sheet(os.path.abspath(args.contact_sheet), ids_in_order)

    for warning in warnings:
        print(f"WARNING: {warning}")
    for problem in problems:
        print(f"PROBLEM: {problem}")
    print(f"Validated {len(manifest)} assets: {len(problems)} problems, {len(warnings)} warnings")
    sys.stdout.flush()
    os._exit(1 if problems else 0)


if __name__ == "__main__":
    try:
        main()
    except Exception:
        import traceback
        traceback.print_exc()
        sys.stdout.flush()
        os._exit(1)
